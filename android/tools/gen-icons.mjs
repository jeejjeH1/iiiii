// Generates ui/SiteIcons.kt: the web app's stroke icons (assets/core.js P) as Compose ImageVectors.
// Usage (from the repo root): node android/tools/gen-icons.mjs
import fs from 'fs';
import path from 'path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const core = fs.readFileSync(root + '/assets/core.js', 'utf8');
const start = core.indexOf('const P = {');
const P = eval('(' + core.slice(core.indexOf('{', start), core.indexOf('\n};', start) + 2) + ')');
// header buttons that only live in index.html
P.sliders = '<path d="M4 7h10M18 7h2M4 17h4M12 17h8"/><circle cx="16" cy="7" r="2"/><circle cx="10" cy="17" r="2"/>';
const attr = (el, k) => { const m = new RegExp(`\\b${k}="([^"]*)"`).exec(el); return m ? m[1] : null; };
const n = (el, k) => +(attr(el, k) || 0);
function toPath(el) {
  const tag = /^<(\w+)/.exec(el)[1];
  if (tag === 'path') return attr(el, 'd');
  if (tag === 'circle') { const cx = n(el, 'cx'), cy = n(el, 'cy'), r = n(el, 'r'); return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
  if (tag === 'ellipse') { const cx = n(el, 'cx'), cy = n(el, 'cy'), rx = n(el, 'rx'), ry = n(el, 'ry'); return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
  if (tag === 'line') return `M${n(el, 'x1')} ${n(el, 'y1')}L${n(el, 'x2')} ${n(el, 'y2')}`;
  if (tag === 'rect') {
    const x = n(el, 'x'), y = n(el, 'y'), w = n(el, 'width'), h = n(el, 'height'), r = Math.min(n(el, 'rx'), w / 2, h / 2);
    if (!r) return `M${x} ${y}h${w}v${h}h${-w}z`;
    return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`;
  }
  return null;
}
let out = `// Generated by android/tools/gen-icons.mjs from the web app's icon set (assets/core.js).
package app.goallive.live.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

private fun icon(name: String, filled: Boolean, vararg d: String): ImageVector {
    val b = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f)
    for (p in d) b.addPath(
        pathData = addPathNodes(p),
        fill = if (filled) SolidColor(Color.Black) else null,
        stroke = SolidColor(Color.Black), strokeLineWidth = 1.8f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,
    )
    return b.build()
}

object Ic {
`;
for (const [k, svg] of Object.entries(P)) {
  const els = svg.match(/<(path|circle|rect|line|ellipse)\b[^>]*>/g) || [];
  const paths = els.map(toPath).filter(Boolean);
  const filled = /fill="currentColor"/.test(svg);
  out += `    val ${k} by lazy { icon("${k}", ${filled}, ${paths.map((p) => JSON.stringify(p)).join(', ')}) }\n`;
}
out += `    val starOn by lazy { icon("starOn", true, ${JSON.stringify(toPath(P.star.match(/<path[^>]*>/)[0]))}) }\n}\n`;
fs.writeFileSync(root + '/android/app/src/main/java/app/goallive/live/ui/SiteIcons.kt', out);
console.log(Object.keys(P).join(' '));
